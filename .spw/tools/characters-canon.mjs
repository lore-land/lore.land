#!/usr/bin/env node
// @ts-check
/**
 * characters-canon.mjs — write the character registry (book/scripts/modules/characters.mjs) out as
 * canon and as a portable sheet, so the two never drift from the module:
 *   .spw/surfaces/characters.spw        each character as its identity spell, with where to meet them
 *   book/content/world/characters.json  the same, with each portrait as a standalone SVG
 *
 *   npm run spw:characters
 */
import { writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { CHARACTERS, MODELS, MOODS, REASONS, WEIGHT, identitySpell, charactersSheet } = await import(resolve(ROOT, 'book/scripts/modules/characters.mjs'));
/** @param {unknown} s */
const q = (s) => String(s).replace(/"/g, "'");
const lines = [
  '# Lore.Land characters (generated by .spw/tools/characters-canon.mjs from book/scripts/modules/characters.mjs; re-run, do not edit)',
  '# Everyone in the book, each as who they are in Spw, where the book first has them, and where to meet them.',
  '# Portraits: portraitSVG() in characters.mjs; standalone SVGs in book/content/world/characters.json.',
  '#>lore_land_surfaces_characters',
  '#:surface #!canon',
  '#:layer #!pragmatics',
  '#:status #!live',
  '',
  '~<rationale>{',
  '  A character is the same everywhere: on a card, in a notice, on the cast, on a print, on another site. One registry, one portrait style, and one spell for who they are, so meeting someone anywhere is meeting the same someone. A character not yet met is a silhouette with a hint of where to meet them.',
  '}',
  '',
  '^characters['
];
Object.entries(CHARACTERS).forEach(([id, c]) => {
  const m = MODELS[id] || {};
  const why = REASONS[id] || {};
  const weight = WEIGHT[id] || {};
  const model = [m.traits?.length && `#traits["${q(m.traits.join(', '))}"]`, m.temperament && `#temperament["${q(m.temperament)}"]`, m.knack && `#knack["${q(m.knack)}"]`, why.want && `?want["${q(why.want)}"]`, why.limit && `.limit["${q(why.limit)}"]`, why.escape && `~escape["${q(why.escape)}"]`, why.reason && `#reason["${q(why.reason)}"]`, weight.carries && `%carries["${q(weight.carries)}"]`, weight.hands_on && `&hands_on["${q(weight.hands_on)}"]`, weight.eased && `~eased["${q(weight.eased)}"]`, weight.ground && `#ground["${q(weight.ground)}"]`].filter(Boolean).join(' ');
  lines.push(`  ${identitySpell(id).replace(/ \}$/, ` &card[${c.card}] #where["${q(c.href)}"] #line["${q(c.line)}"]${model ? ` ${model}` : ''} }`)}`);
});
lines.push(']', '');
lines.push('^moods{', `  marks: "${MOODS.join(' · ')}: worn on the face, and drawn as the marks comics use beside a head (strokes, a bead of sweat, a bang, a question), so any portrait can wear any mood; the figure in plain lines has only the marks; portraitSVG(id, { mood }) and <lore-portrait mood>"`, '  in_the_lanes: "the carriers faces in Exactly One Pie follow the carry: calm, focused on the needle, glad after a WAP, worried as the pie tilts, ouch at a knock"', '}', '');
await writeFile(resolve(ROOT, '.spw/surfaces/characters.spw'), lines.join('\n'));
await writeFile(resolve(ROOT, 'book/content/world/characters.json'), `${JSON.stringify({ note: 'Generated by .spw/tools/characters-canon.mjs from book/scripts/modules/characters.mjs. Each portrait is a standalone SVG.', characters: charactersSheet() }, null, 2)}\n`);
console.log(`[spw:characters] ${Object.keys(CHARACTERS).length} characters → .spw/surfaces/characters.spw, book/content/world/characters.json`);
