#!/usr/bin/env node
// @ts-check
/**
 * way-canon.mjs — write book/content/world/way.json out as canon, in the workbench's wonder form, so the two never drift:
 *   .spw/surfaces/reasons.spw   why each chapter is here; each chapter's wonder as a line one edit past what reads; who can be kept apart
 *
 *   npm run spw:way
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { wayForks } from '../../book/scripts/modules/forks.mjs';
import { TOTAL_CHAPTERS } from '../../book/scripts/modules/book-extent.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
/** @type {import('../../book/schema/book-types.mjs').WayData} */
const way = JSON.parse(await readFile(resolve(ROOT, 'book/content/world/way.json'), 'utf8'));
/** @param {unknown} s */
const q = (s) => String(s).replace(/"/g, "'");
/** @param {number | string} n */
const pad = (n) => String(n).padStart(2, '0');
const lines = [
  '# Lore.Land reasons (generated by .spw/tools/way-canon.mjs from book/content/world/way.json; re-run, do not edit)',
  '# Why each chapter is in the book, what it holds for the chapters after it, one wonder a single edit past a room of it, and who can be kept apart.',
  '# Wonder form: .spw/_workbench/docs/theory/spw/wonder-field.spw. A wonder is a line one edit past what already reads; its measures name the ways it could come out; its probe is the act that tells.',
  '#>lore_land_surfaces_reasons',
  '#:surface #!canon',
  '#:layer #!pragmatics',
  '#:status #!live',
  '',
  '~<rationale>{',
  '  A book can say why it is the way it is without explaining itself. Each chapter here has a reason in the register of its maker, shown folded at the end of the chapter, and one question a reader can guess at before reading on. The guess is the expect, a later chapter is the probe, and the answer is what the reader says. Nothing here scores it. Some wonders have no probe. They are kept open on purpose, and nothing may close them in passing.',
  '}',
  '',
  '^reasons['
];
Object.entries(way.chapters).forEach(([n, c]) => lines.push(`  @c${pad(n)}{ #why["${q(c.reason)}"] .holds["${q(c.holds)}"] }`));
lines.push(']', '', '?wonders[');
Object.entries(way.chapters).forEach(([n, c]) => {
  const w = c.wonder;
  const probe = w.probe ? `~#probe(read): "book/chapter/${pad(w.probe)}"` : '~#open: "on purpose"';
  lines.push(`  ?c${pad(n)}{ ~#with: "${q(w.line)}" ~#edit: "${q(w.edit)}" #says["${q(w.says)}"] #asks["${q(w.asks)}"] $%[${w.ways.map((a) => `"${q(a)}"`).join(', ')}] ${probe} }`);
});
lines.push(']', '', '!company{');
way.pairs.forEach((p) => lines.push(`  *${p.id}{ &who["${p.who.join(', ')}"] #name["${q(p.name)}"] #primes["${q(p.primes)}"] #why["${q(p.why)}"] #costs["${q(p.costs)}"] ${p.aside ? `!aside[${p.aside.join(', ')}] ` : ''}%swaps[${(p.rooms || []).reduce((sum, r) => sum + r.swaps.length, 0)}] }`));
lines.push('}', '', '# Every choice of the way is also a fork: what forks, on what, and where each side goes (book/scripts/modules/forks.mjs).', '# boon leans forward, the book as it stands; bane leans inverse, the book turned from itself. Drawn at a chapter end under the forks trial.', '?forks[');
wayForks(way, TOTAL_CHAPTERS).forEach((f) => lines.push(`  ${f.line}`));
lines.push(']', '', '^held[');
way.held.forEach((h) => lines.push(`  { &who["${h.who.join(', ')}"] #why["${q(h.why)}"] }`));
lines.push(']', '');
await writeFile(resolve(ROOT, '.spw/surfaces/reasons.spw'), lines.join('\n'));
console.log(`[spw:way] ${Object.keys(way.chapters).length} chapters, ${way.pairs.length} pairings, ${wayForks(way, TOTAL_CHAPTERS).length} forks → .spw/surfaces/reasons.spw`);
