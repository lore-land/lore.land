#!/usr/bin/env node
/**
 * progression-audit.mjs — the sense of progression, chapter by chapter, and every collectible
 * screen, evaluated as Spw.
 *
 *   node .spw/tools/progression-audit.mjs        (npm run spw:progression)
 *
 * Writes .spw/audits/progression.spw: for each chapter, what reading it and carrying it offer
 * (rooms, wonders first met, people first met, things the lanes introduce, lore grounded there, its
 * palette) and the curve they make across the book; flags where the curve sags or spikes, where the
 * game and the story do not yet feed each other; and every collectible screen with what it counts
 * and what it promises next. Counts are read from the canon; the screens block is the evaluation.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = async (p) => JSON.parse(await readFile(resolve(ROOT, p), 'utf8'));
const pad = (n) => String(n).padStart(2, '0');

const almanac = await read('book/content/world/almanac.json');
const palettes = await read('book/content/world/palettes.json');
const lore = await read('book/content/world/pie-lore.json');
const { CHARACTERS } = await import(resolve(ROOT, 'book/scripts/modules/characters.mjs'));
// The lanes introduce things chapter by chapter (INTRO in pie-game.mjs, read as text: the module is for the page).
const game = await readFile(resolve(ROOT, 'book/scripts/home/pie-game.mjs'), 'utf8');
const introBlock = (/const INTRO = Object\.freeze\(\{([\s\S]*?)\}\);/.exec(game) || [])[1] || '';
const intro = {};
[...introBlock.matchAll(/([a-z]+):\s*(\d+)/g)].forEach(([, kind, n]) => { (intro[n] = intro[n] || []).push(kind); });

const chapters = [];
for (let n = 1; n <= 15; n += 1) {
  let data;
  try { data = await read(`book/content/chapters/${pad(n)}.json`); } catch { continue; }
  const rooms = (data.sections || []).filter((s) => s.room).length;
  const wonders = (almanac.wonders || []).filter((w) => Number(w.home) === n).length;
  const people = Object.values(CHARACTERS).filter((c) => Number(c.first) === n).length;
  const lanes = (intro[n] || []).length;
  const lines = (lore.lines || []).filter((l) => Number(l.ground?.chapter) === n).length;
  const palette = (palettes.palettes || []).filter((p) => Number(p.chapter) === n).length;
  const total = wonders + people + lanes + lines + palette;
  chapters.push({ n, title: data.title, rooms, wonders, people, lanes, lines, palette, total, laneKinds: intro[n] || [] });
}
const avg = chapters.reduce((s, c) => s + c.total, 0) / Math.max(1, chapters.length);
let running = 0;
const q = (s) => String(s).replace(/"/g, "'");
const lines = [
  '# Lore.Land progression (generated by .spw/tools/progression-audit.mjs; do not edit by hand, re-run it)',
  '# The sense of progression, chapter by chapter, and every collectible screen, evaluated as Spw.',
  '#>lore_land_audits_progression',
  '#:surface #!audit',
  '#:layer #!pragmatics',
  '#:status #!seeded',
  '',
  '~<rationale>{',
  '  A reader should feel the book open as they go, and a player should feel the lanes open with it. Each chapter offers something to keep in each way of reading it, and each thing kept should point somewhere further. This audit counts what each chapter offers, draws the curve those counts make, and names where the story and the game do not yet feed each other.',
  '}',
  '',
  '%chapters{'
];
chapters.forEach((c) => {
  running += c.total;
  lines.push(`  c${pad(c.n)}: { title: "${q(c.title)}" rooms: ${c.rooms} wonders: ${c.wonders} people: ${c.people} lanes: ${c.lanes} lore: ${c.lines} palette: ${c.palette} total: ${c.total} so_far: ${running} lanes_bring: "${c.laneKinds.join(' ') || 'nothing new'}" }`);
});
lines.push('}', '');
const flags = [];
chapters.forEach((c) => {
  if (!c.lines) flags.push(`c${pad(c.n)}_no_lore: "the pies say nothing grounded in ${q(c.title)}: a line here would give its rooms something to unlock in the lanes"`);
  if (c.total < avg * 0.5) flags.push(`c${pad(c.n)}_lull: "${q(c.title)} offers ${c.total} against an average of ${avg.toFixed(1)}: a lull, unless it is a rest on purpose"`);
  if (c.total > avg * 1.8) flags.push(`c${pad(c.n)}_spike: "${q(c.title)} offers ${c.total}: much to take in at once"`);
  if (c.lanes >= 6) flags.push(`c${pad(c.n)}_lane_load: "the lanes bring ${c.lanes} new things in ${q(c.title)}: a lot to learn in one chapter"`);
  if (!c.palette) flags.push(`c${pad(c.n)}_no_palette: "${q(c.title)} has no palette of its own to earn"`);
});
lines.push('?flags{', ...flags.map((f) => `  ${f}`), '}', '');
lines.push(
  '^exchange{',
  '  story_to_game: "rooms read in a chapter steady the pie there (up to a third); every room read makes the pies say the lore grounded in that chapter; reading turns cards that the deck keeps; wonders kept in the almanac give gifts in the lanes"',
  '  game_to_story: "lore heard in the lanes is set beside the room it is about (lanes-lore.mjs); carries lean a chapter reading (pie-projection.mjs); cards met in the lanes count in the chapter inventory; a carried chapter wears its palette layer"',
  '  measure: "each exchange is a promise on both sides: the page says what the lanes will give, and the lanes say what the page holds"',
  '}',
  '',
  '^screens{',
  '  almanac: { counts: "72 wonders, 16 palettes, the cards" empty: "veiled shapes with hints of where to look" half: "a shelf with gaps that say where" full: "a combining bench of what was kept" next: "the nearest unkept wonder names its room" }',
  '  deck: { counts: "every card in the lanes, face up or down" empty: "card backs by type" half: "turned cards with their spells and what they are worth" full: "a deck to pass along as spells" next: "a face-down card says not met yet; the chapter that brings it could say where" }',
  '  chapter_inventory: { counts: "every expression a chapter holds, by sigil" empty: "a description spell veiled where unfound" half: "n of m found, by sigil, each lit and walkable" full: "the chapter whole, its spell plain" next: "an unfound item says which room to look in" }',
  '  cast: { counts: "11 people" empty: "silhouettes with where to meet them" half: "you have met n of 7" full: "every portrait, every mood on the model sheet" next: "the first silhouette names its chapter" }',
  '  carries: { counts: "15 chapters carried, each leaned three ways" empty: "not carried yet" half: "a lean bar a chapter" full: "the whole book leaned by how you carried it" next: "the chapter after the last carried" }',
  '  lore: { counts: "every line from the two pies, one or more grounded in each chapter" empty: "locked lines with their way in" half: "lines set in their rooms on the page" full: "both voices whole" next: "a locked line says the game way and the reading way" }',
  '  atlas: { counts: "27 studies" empty: "veiled in chapter colours" half: "glimpsed through a window shaped like their room" full: "kept whole" next: "find similar walks from any study to the book" }',
  '  progress_spell: { counts: "rooms, wonders, cards, palettes, lore, people" empty: "a spell of zeros that still plays" half: "a spell to copy and compare" full: "a spell of a reader who has been everywhere" next: "^next names the chapter with the most still to find" }',
  '}',
  ''
);
await writeFile(resolve(ROOT, '.spw/audits/progression.spw'), lines.join('\n'));
console.log(`[spw:progression] ${chapters.length} chapters, ${flags.length} flags, average ${avg.toFixed(1)} a chapter → .spw/audits/progression.spw`);
